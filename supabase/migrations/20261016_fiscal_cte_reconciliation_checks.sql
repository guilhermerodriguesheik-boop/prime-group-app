-- Provider reconciliation audit. An indeterminate fiscal transmission is never deleted
-- merely because the provider's list is empty.
create table if not exists public.fiscal_cte_reconciliation_checks (
 id bigint generated by default as identity primary key,
 attempt_id uuid not null references public.fiscal_cte_transmissions(id) on delete restrict,
 checked_at timestamptz not null default now(),
 list_http_status integer,
 emitter_profile_http_status integer,
 documents_scanned integer not null default 0,
 possible_matches jsonb not null default '[]'::jsonb,
 emitter_profile_summary jsonb not null default '{}'::jsonb,
 result_note text not null,
 constraint fiscal_cte_reconciliation_matches_array check (jsonb_typeof(possible_matches)='array')
);
create index if not exists fiscal_cte_reconciliation_recent_idx on
 public.fiscal_cte_reconciliation_checks(attempt_id,checked_at desc);
alter table public.fiscal_cte_reconciliation_checks enable row level security;
revoke all on public.fiscal_cte_reconciliation_checks from anon, authenticated;
comment on table public.fiscal_cte_reconciliation_checks is
 'Read-only vendor evidence. Absence from list is not proof of non-issuance; never automatically unlocks/reissues CT-e.';
